package com.mall.coupon.config;

import java.util.function.Supplier;

/**
 * 秒杀接口的并发闸门（bulkhead）。
 *
 * <h3>为什么在换成虚拟线程之后【必须】补上这个东西</h3>
 * 改造之前，秒杀接口靠 Callable + 一个有界线程池（core 50 / max 200 / queue 2000）做异步
 * servlet 处理。那个线程池除了"别占着 Tomcat 线程等 MQ 确认"之外，还在【隐式地承担限流】：
 * 在途请求超过 2200 个，线程池就开始拒绝任务，多余的流量被干脆利落地挡在业务逻辑之外。
 * <p>
 * 虚拟线程把这个天花板拿掉了 —— 阻塞变得极廉价，Tomcat 会乐意为每个请求开一个虚拟线程，
 * 上限变成 server.tomcat.max-connections（默认 8192）。看起来是"扛得更多了"，
 * 实际上只是把排队的位置往下游挪：真正的瓶颈变成 HikariCP 的连接数（默认 10）。
 * 于是失败模式从【干净地拒绝一部分请求】退化成【所有人一起卡在获取数据库连接、
 * 然后集体超时】—— 后者对下游更凶险，对用户体验也更差，而且排查时看到的是满屏
 * connection acquisition timeout，很难一眼看出根因是入口没有限流。
 * <p>
 * 所以这个闸门做的事，就是把原来"藏在线程池尺寸里的限流"变成一个【显式的、可调的、
 * 有名字的】东西。这也是把并发上限和"用多少线程"解耦：以前想调限流阈值只能去改线程池
 * 大小，两件事被迫绑在一起；现在各调各的。
 *
 * <h3>为什么是立即失败，而不是排队等待</h3>
 * 秒杀的特点是"绝大多数请求注定抢不到"。让抢不到的人排队等，只是把失败延后、
 * 同时把资源占住。立刻返回"系统繁忙"比让用户等 10 秒再失败更好，也让上游
 * （网关的令牌桶限流）能更快看到压力。
 *
 * <h3>和网关限流的关系：两层是互补的，不是重复</h3>
 * 网关那层（RequestRateLimiter）限的是【速率】（每秒多少个），防的是流量洪峰；
 * 这一层限的是【在途并发数】，防的是"请求都进来了但下游处理不过来、堆在这里"。
 * 一个慢下游会让速率限流失效（每秒放进来 50 个，但每个要 10 秒，在途就堆到 500），
 * 并发限流才管得住这种情况。
 *
 * <h3>为什么抽成接口：两种实现要能对照</h3>
 * <ul>
 *   <li>{@link StaticSeckillBulkhead}：固定容量的信号量。简单、可预测，
 *       但那个固定值必须在「冷启动容量」和「热态容量」之间做折中，而实测这两者
 *       差一个数量级。</li>
 *   <li>{@link AdaptiveSeckillBulkhead}：按观测到的延迟动态调整限额。
 *       形状上对症，但引入了一个会自己变的量，行为更难预测。</li>
 * </ul>
 * 保留两个而不是直接替换，是因为这套环境的测量噪声很大 —— 同一配置两轮之间的
 * p95 能差一个数量级（664ms 对 91ms，见 JdbcObservationAutoConfiguration 的记录）。
 * <b>没有对照组就无法判断自适应到底有没有更好</b>，所以切换开关本身是实验器材，
 * 不只是"逃生舱"。用 {@code mall.seckill.bulkhead.mode} 切（见
 * {@link SeckillBulkheadConfiguration}）。
 */
public interface SeckillBulkhead {

    /**
     * 在闸门内执行。
     *
     * @param action   实际业务
     * @param rejected 没拿到通行证时的返回值（快速失败）
     */
    <T> T call(Supplier<T> action, Supplier<T> rejected);

    /**
     * 当前的并发上限。
     * <p>
     * 静态实现下这是个常量；<b>自适应实现下它会随时间变化</b>，那条曲线本身就是
     * 最有价值的观测量 —— 能直接看出算法在什么时候收紧、什么时候放开。
     */
    int capacity();

    /** 当前还能放进来多少个（上限减去在途数）。长期贴近 0 说明闸门已成为瓶颈。 */
    int availablePermits();

    /** 累计被挡下的请求数。持续增长说明容量或下游能力需要重新评估。 */
    long rejectedCount();
}

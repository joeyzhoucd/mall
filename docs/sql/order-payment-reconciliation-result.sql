CREATE TABLE IF NOT EXISTS oms_payment_reconciliation_result (
  id BIGINT NOT NULL AUTO_INCREMENT COMMENT 'id',
  reconcile_date DATE NOT NULL COMMENT 'reconciliation date',
  row_type VARCHAR(16) NOT NULL COMMENT 'statement row type: PAYMENT/REFUND',
  channel VARCHAR(32) NOT NULL COMMENT 'payment channel: alipay/wechat/credit_card',
  order_sn VARCHAR(64) NOT NULL COMMENT 'order number',
  trade_no VARCHAR(96) NOT NULL COMMENT 'gateway trade number',
  refund_sn VARCHAR(64) DEFAULT NULL COMMENT 'refund number',
  refund_sn_key VARCHAR(64) GENERATED ALWAYS AS (IFNULL(refund_sn, '')) STORED COMMENT 'normalized refund number for unique key',
  gateway_amount DECIMAL(18, 2) DEFAULT NULL COMMENT 'gateway amount',
  local_amount DECIMAL(18, 2) DEFAULT NULL COMMENT 'local amount',
  gateway_status VARCHAR(32) DEFAULT NULL COMMENT 'gateway status',
  local_status VARCHAR(32) DEFAULT NULL COMMENT 'local status',
  currency VARCHAR(16) DEFAULT NULL COMMENT 'currency',
  difference_type VARCHAR(64) NOT NULL COMMENT 'difference type: MATCH/LOCAL_MISSING/AMOUNT_MISMATCH/STATUS_MISMATCH',
  process_status VARCHAR(32) NOT NULL COMMENT 'process status: resolved/pending',
  raw_line TEXT DEFAULT NULL COMMENT 'raw statement line',
  create_time DATETIME NOT NULL COMMENT 'create time',
  update_time DATETIME NOT NULL COMMENT 'update time',
  PRIMARY KEY (id),
  UNIQUE KEY uk_payment_reconcile_row (reconcile_date, row_type, channel, order_sn, trade_no, refund_sn_key),
  KEY idx_payment_reconcile_process (process_status, difference_type),
  KEY idx_payment_reconcile_order_sn (order_sn),
  KEY idx_payment_reconcile_trade_no (trade_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='payment reconciliation result';
